CREATE TABLE app_users (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) NOT NULL UNIQUE,
    password VARCHAR2(255) NOT NULL,
    email VARCHAR2(100),
    phone VARCHAR2(20),
    role VARCHAR2(20) NOT NULL,
    account_locked NUMBER(1) DEFAULT 0 NOT NULL,
    account_enabled NUMBER(1) DEFAULT 1 NOT NULL,
    password_expired NUMBER(1) DEFAULT 0 NOT NULL,
    failed_login_attempts NUMBER(5) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE system_config (
    config_key VARCHAR2(50) PRIMARY KEY,
    config_value VARCHAR2(255) NOT NULL
);

CREATE TABLE payment_transaction (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR2(100) NOT NULL UNIQUE,
    provider VARCHAR2(50) NOT NULL,
    handler_id VARCHAR2(100),
    amount NUMBER(15,2) NOT NULL,
    currency VARCHAR2(10) NOT NULL,
    payer_id VARCHAR2(100),
    status VARCHAR2(50) NOT NULL,
    gateway_tx_id VARCHAR2(100),
    description VARCHAR2(255),
    created_by VARCHAR2(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE maker_checker_request (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_type VARCHAR2(50) NOT NULL,
    maker_user VARCHAR2(50) NOT NULL,
    checker_user VARCHAR2(50),
    status VARCHAR2(20) NOT NULL,
    payload_json VARCHAR2(4000),
    remarks VARCHAR2(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE audit_log (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50),
    action VARCHAR2(100) NOT NULL,
    details VARCHAR2(500),
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
